#!/usr/bin/env python3
"""Generate src/assets/web_assets.h from reference/python-app/frontend/.

The frontend is served straight out of flash (PROGMEM): the Python app opened
frontend/main.html and main.js per request, so the bytes here are the exact
same files. Re-run after any frontend edit:

    python3 scripts/embed_assets.py

Stdlib only; output is deterministic apart from the content hash header.
"""

import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "reference" / "python-app" / "frontend"
OUT = ROOT / "src" / "assets" / "web_assets.h"

ASSETS = [("main.html", "MAIN_HTML"), ("main.js", "MAIN_JS")]

# R"catbox(...)catbox" raw string delimiters are safe: the frontend files
# contain no such sequence (checked below).
DELIM = "catbox"


def embed(path: pathlib.Path, symbol: str) -> str:
    data = path.read_bytes()
    text = data.decode("utf-8")
    if f")" + DELIM + ')"' in text:
        sys.exit(f"{path}: contains a raw-string terminator; pick another delimiter")
    digest = hashlib.sha256(data).hexdigest()[:16]
    # Bytes are served verbatim (Python served file.read()), so the raw
    # string must contain the file content with nothing added or stripped.
    return (
        f"// {path.relative_to(ROOT)} — sha256:{digest}, {len(data)} bytes\n"
        f'static const char {symbol}[] PROGMEM = R"{DELIM}({text}){DELIM}";\n'
    )


def main() -> None:
    parts = [
        "// GENERATED by scripts/embed_assets.py — do not edit by hand.\n"
        "// Source of truth: reference/python-app/frontend/\n#pragma once\n\n"
        '#include <pgmspace.h>\n\n'
    ]
    for name, symbol in ASSETS:
        src = FRONTEND / name
        if not src.is_file():
            sys.exit(f"missing frontend asset: {src}")
        parts.append(embed(src, symbol))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
